"""
subject_report.py — Word report for ONE teacher + subject, sections pooled.
Contains no section, email, name or timestamp. Comments are shown word for
word (after any HR edit), unlabelled and in a fixed random order.
"""

from __future__ import annotations

import io
import random

from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

import db
import utils
from report import _add_heading, _rating_table, ACCENT  # reuse the existing styling helpers

MIN_RESPONDENTS = 5


def weighted_average(rows):
    pairs = [(r["avg_rating"], r["n"]) for r in rows if r["avg_rating"] is not None and r["n"]]
    total = sum(n for _, n in pairs)
    return sum(a * n for a, n in pairs) / total if total else None


def category_averages(rows):
    cats: dict = {}
    for r in rows:
        if r["avg_rating"] is None or not r["n"]:
            continue
        c = cats.setdefault(r["category"], [0.0, 0])
        c[0] += r["avg_rating"] * r["n"]
        c[1] += r["n"]
    return [(cat, s / n) for cat, (s, n) in cats.items()]


def visible_comments(activity_ids, seed: str) -> dict:
    by_cat: dict = {}
    for r in db.get_pooled_open_ended_answers(activity_ids):
        if r["hidden"]:
            continue
        text = (r["edited_text"] if r["edited_text"] is not None else r["original_text"]).strip()
        if text:
            by_cat.setdefault(r["category"], []).append(text)
    rng = random.Random(seed)
    for items in by_cat.values():
        items.sort()          # drop the submission order first...
        rng.shuffle(items)    # ...then shuffle (same order every download)
    return dict(sorted(by_cat.items()))


def build_subject_report(group: dict) -> bytes:
    ids = group["activity_ids"]
    if not group["all_closed"]:
        raise ValueError("Close every section of this subject before generating the report.")
    n = db.count_responses_for(ids)
    if n < MIN_RESPONDENTS:
        raise ValueError(f"Not enough responses yet (minimum {MIN_RESPONDENTS}).")

    rating_rows = db.get_pooled_rating_summary(ids)
    overall = weighted_average(rating_rows)
    seed = f'{group["teacher_name"]}|{group["subject"]}|{group["school_year"]}|{group["term"]}'
    comments = visible_comments(ids, seed)

    doc = Document()

    title = doc.add_heading("Student Evaluation of Teacher", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in title.runs:
        run.font.color.rgb = ACCENT

    name = doc.add_paragraph(group["teacher_name"])
    name.alignment = WD_ALIGN_PARAGRAPH.CENTER
    name.runs[0].font.size = Pt(16)
    name.runs[0].bold = True

    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta.add_run(" · ".join(b for b in [
        group["subject"], " ".join(x for x in [group["school_year"], group["term"]] if x)
    ] if b)).italic = True

    _add_heading(doc, "Overview", level=1)
    p = doc.add_paragraph()
    p.add_run("Number of student respondents: ").bold = True
    p.add_run(str(n))
    if overall is not None:
        p = doc.add_paragraph()
        p.add_run("Overall average rating: ").bold = True
        p.add_run(f"{overall:.2f} out of 5")
    p = doc.add_paragraph()
    p.add_run("Rating scale: ").bold = True
    p.add_run(utils.rating_scale_help())

    _add_heading(doc, "Average per Area", level=1)
    _rating_table(doc, [(c, f"{a:.2f}") for c, a in category_averages(rating_rows)],
                  ["Area", "Avg. Rating (1–5)"])

    _add_heading(doc, "Average per Item", level=1)
    _rating_table(
        doc,
        [(r["question_text"], f'{r["avg_rating"]:.2f}' if r["avg_rating"] is not None else "—", r["n"])
         for r in rating_rows],
        ["Item", "Avg. Rating (1–5)", "# Ratings"],
    )

    _add_heading(doc, "Comments and Suggestions", level=1)
    note = doc.add_paragraph(
        "Comments are shown as the students wrote them, in random order. Any detail that could "
        "identify a student has been replaced with [removed]."
    )
    note.runs[0].italic = True
    if comments:
        for cat, items in comments.items():
            doc.add_heading(cat, level=2)
            for text in items:
                doc.add_paragraph(text, style="List Bullet")
    else:
        doc.add_paragraph("No comments were submitted.")

    doc.add_paragraph()
    doc.add_paragraph("Generated by the DBES Teacher Evaluation System.").runs[0].italic = True

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
